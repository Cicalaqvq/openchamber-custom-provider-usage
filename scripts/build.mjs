import { build } from "esbuild";
import { hasGuestPage, requestedGuestCapabilities, resolveStatusSectionEntry } from "@openchamber/sdk";
import { parseManifest } from "@openchamber/sdk/schemas";
import { lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve, basename } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageInfo = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const GENERATED_MARKER = ".openchamber-custom-provider-usage-build";
const MARKER_TEXT = "Generated by openchamber-custom-provider-usage build script.\n";
const DEFAULT_OUTPUT = join(root, "dist", "extension");

/** Pages and their bundles; each entry is a separate sandboxed document. */
const PAGES = [
  { entry: "panel/index.html", source: "src/panel-main.ts", script: "main.js" },
  { entry: "status/index.html", source: "src/status-main.ts", script: "main.js" },
];
const SERVICE_ENTRY = "service/main.js";

export function createManifest() {
  const contributes = structuredClone(packageInfo.openchamber.contributes);
  for (const item of [contributes.panel, contributes.statusSection, contributes.service]) {
    if (!item.entry.startsWith("dist/extension/")) throw new Error(`根 manifest entry 必须位于 dist/extension：${item.entry}`);
    item.entry = item.entry.slice("dist/extension/".length);
  }
  return {
    name: packageInfo.name,
    version: packageInfo.version,
    license: packageInfo.license,
    openchamber: { ...packageInfo.openchamber, contributes },
  };
}

function checkManifest(manifest, rootManifest = false) {
  const parsed = parseManifest(manifest);
  if (!parsed.ok) throw new Error(`SDK manifest 验证失败：${parsed.message}`);
  const contributes = parsed.manifest.contributes;
  if (!hasGuestPage(contributes)) throw new Error("manifest 必须声明 panel.entry");
  const prefix = rootManifest ? "dist/extension/" : "";
  if (resolveStatusSectionEntry(contributes) !== `${prefix}status/index.html`) throw new Error("manifest statusSection entry 无效");
  if (contributes.service?.entry !== `${prefix}${SERVICE_ENTRY}` || contributes.service.runtime !== "host") {
    throw new Error("manifest service entry 无效");
  }
  const capabilities = requestedGuestCapabilities(contributes);
  if (capabilities.length !== 1 || capabilities[0] !== "service") throw new Error(`扩展权限范围异常：${capabilities.join(", ")}`);
  return parsed.manifest;
}

export function validateManifest() {
  checkManifest(packageInfo, true);
  const manifest = createManifest();
  checkManifest(manifest);
  return manifest;
}

export async function outputMarked(destination = DEFAULT_OUTPUT) {
  try {
    const marker = await readFile(join(destination, GENERATED_MARKER), "utf8");
    if (marker !== MARKER_TEXT) return false;
    const manifest = JSON.parse(await readFile(join(destination, "package.json"), "utf8"));
    return manifest.name === packageInfo.name;
  } catch { return false; }
}

function assertAllowedOutput(destination, testOutput) {
  if (!testOutput) {
    if (destination !== resolve(DEFAULT_OUTPUT)) throw new Error("构建输出路径只能是项目 dist/extension；不支持自定义 --out");
    return;
  }
  const testRoot = resolve(tmpdir(), "opencode");
  if (dirname(destination) !== testRoot || !basename(destination).startsWith("openchamber-custom-provider-usage-test-")) {
    throw new Error("测试构建输出必须是批准临时目录中的专用测试目录");
  }
}

const BROWSER = { absWorkingDir: root, bundle: true, format: "iife", platform: "browser", target: ["es2022"], metafile: true, logLevel: "silent", charset: "utf8" };

/** Test-only output override is restricted to an isolated directory under the approved temp root. */
export async function buildExtension(testOutput) {
  const manifest = validateManifest(); // Validate all input/SDK contributions before touching output.
  const destination = resolve(testOutput ?? DEFAULT_OUTPUT);
  assertAllowedOutput(destination, testOutput !== undefined);
  const stylePath = join(root, "src", "styles.css");
  const pages = await Promise.all(PAGES.map(async (page) => {
    const template = await readFile(join(root, page.entry), "utf8");
    if (!template.includes('id="root"') || !template.includes('href="styles.css"') || !template.includes(`src="${page.script}"`)) {
      throw new Error(`${page.entry} 模板必须引用 #root、styles.css 和 ${page.script}`);
    }
    return { ...page, template };
  }));
  const parent = dirname(destination);
  await mkdir(parent, { recursive: true });
  let existing;
  try { existing = await lstat(destination); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (existing && (!existing.isDirectory() || existing.isSymbolicLink() || !await outputMarked(destination))) {
    throw new Error(`拒绝覆盖非本工具生成的目录：${destination}`);
  }

  const staging = await mkdtemp(join(parent, ".openchamber-custom-provider-usage-stage-"));
  let backup;
  let movedOld = false;
  try {
    const bundled = new Set();
    for (const page of pages) {
      const directory = join(staging, dirname(page.entry));
      await mkdir(directory, { recursive: true });
      await writeFile(join(staging, page.entry), page.template);
      const result = await build({ ...BROWSER, entryPoints: [join(root, page.source)], outfile: join(directory, page.script) });
      for (const input of Object.values(result.metafile.outputs).flatMap(output => Object.keys(output.inputs))) bundled.add(input);
    }
    const service = await build({
      ...BROWSER,
      absWorkingDir: root,
      platform: "node",
      entryPoints: [join(root, "src", "service.ts")],
      outfile: join(staging, SERVICE_ENTRY),
      // No externals: the host runs the file as-is, with no package dependencies next to it.
      packages: "bundle",
    });
    for (const input of Object.values(service.metafile.outputs).flatMap(output => Object.keys(output.inputs))) bundled.add(input);

    const thirdParty = [...bundled].filter(input => input.startsWith("node_modules/") && !input.startsWith("node_modules/@openchamber/sdk/"));
    if (thirdParty.length) throw new Error(`bundle 含尚未声明许可证的第三方代码：${thirdParty.join(", ")}`);

    await writeFile(join(staging, "status", "styles.css"), await readFile(stylePath));
    await writeFile(join(staging, "panel", "styles.css"), await readFile(stylePath));
    await writeFile(join(staging, "package.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    await writeFile(join(staging, "LICENSE"), await readFile(join(root, "LICENSE")));
    await writeFile(join(staging, "README.md"), "# OpenChamber Custom Provider Usage\n\n在 Work Status 中显示多个 New API 中转站的余额，站点、令牌和刷新间隔都在扩展面板内配置。请参阅项目 README 了解安全、兼容及第三方许可说明。\n");
    await mkdir(join(staging, "third-party"), { recursive: true });
    await writeFile(join(staging, "third-party", "openchamber-sdk-LICENSE.txt"), await readFile(join(root, "node_modules", "@openchamber", "sdk", "LICENSE")));
    await writeFile(join(staging, "THIRD_PARTY_NOTICES.txt"), await readFile(join(root, "THIRD_PARTY_NOTICES.txt")));
    await writeFile(join(staging, GENERATED_MARKER), MARKER_TEXT);

    if (existing) {
      backup = await mkdtemp(join(parent, ".openchamber-custom-provider-usage-backup-"));
      await rm(backup, { recursive: true, force: true });
      await rename(destination, backup);
      movedOld = true;
    }
    try { await rename(staging, destination); }
    catch (error) {
      if (movedOld) await rename(backup, destination);
      movedOld = false;
      throw error;
    }
    if (movedOld) {
      await rm(backup, { recursive: true, force: true });
      movedOld = false;
    }
    return destination;
  } finally {
    await rm(staging, { recursive: true, force: true });
    // If final installation failed, restoration above has already retained the previous artifact.
    if (backup && !movedOld) {
      try { await lstat(backup); await rm(backup, { recursive: true, force: true }); } catch { /* removed or restored */ }
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const destination = resolve(DEFAULT_OUTPUT);
  try {
    const args = process.argv.slice(2);
    if (args.length > 0) throw new Error("构建不再接受参数：站点在扩展面板中配置，无需重新构建");
    const built = await buildExtension();
    console.log(`扩展已构建：${built}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : "构建失败");
    if (await outputMarked(destination)) console.error("旧产物未更改。");
    process.exitCode = 1;
  }
}
